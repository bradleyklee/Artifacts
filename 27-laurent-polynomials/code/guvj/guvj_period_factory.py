#!/usr/bin/env python3
"""Derive an exact order-two G,U,V,J certificate for a Laurent period.

Input:
    F(x,y) in Q[x^+/-1,y^+/-1].

Definitions:
    rho = 1 - t*F,
    Phi(t) = CT_xy(1/rho),
    Dx = x*d/dx,  Dy = y*d/dy,
    G(a,bx,by) = rho*a - Dx(rho)*bx - Dy(rho)*by,
    J(bx,by) = Dx(bx) + Dy(by).

For w = F^2, solve
    G[U;V] = E*w,
    U - J*V/2 = alpha*rho + beta*F.

The reduced columns for Phi, Phi', Phi'' give an operator
    A = p2(t)*D_t^2 + p1(t)*D_t + p0(t)
and the exact divergence certificate
    Xi = p2*V.

All correctness checks use explicit coefficient comparison.  The program does
not call a generic algebraic simplifier.  Reference terms are generated by
lattice convolution and checked independently by direct power expansion for the
first few powers.
"""
from __future__ import annotations

